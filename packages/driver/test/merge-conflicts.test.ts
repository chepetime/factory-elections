// Lockfile and generated-file conflicts are the factory's to resolve: it regenerates them, outside the sandbox.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import * as git from '@factory/adapters-git';
import { runShell } from '@factory/adapters-process';
import { mergeBase } from '../src/merge-conflicts.ts';

const sh = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8' });

/** A repository whose `feature` and `main` both changed the lockfile (and maybe another file). */
async function diverged(alsoConflict: boolean) {
  const repo = await mkdtemp(join(tmpdir(), 'factory-merge-'));
  sh(repo, 'init', '-q', '-b', 'main');
  sh(repo, 'config', 'user.name', 't');
  sh(repo, 'config', 'user.email', 't@example.com');
  await writeFile(join(repo, 'package.json'), '{"name":"x","version":"1.0.0","private":true}\n');
  await writeFile(join(repo, 'pnpm-lock.yaml'), "lockfileVersion: '9.0'\n# base\n");
  await writeFile(join(repo, 'notes.md'), 'base\n');
  sh(repo, 'add', '.');
  sh(repo, 'commit', '-qm', 'base');
  sh(repo, 'switch', '-qc', 'feature');
  await writeFile(join(repo, 'pnpm-lock.yaml'), "lockfileVersion: '9.0'\n# feature\n");
  if (alsoConflict) await writeFile(join(repo, 'notes.md'), 'feature\n');
  sh(repo, 'commit', '-qam', 'feature');
  sh(repo, 'switch', '-q', 'main');
  await writeFile(join(repo, 'pnpm-lock.yaml'), "lockfileVersion: '9.0'\n# main\n");
  if (alsoConflict) await writeFile(join(repo, 'notes.md'), 'main\n');
  sh(repo, 'commit', '-qam', 'main');
  sh(repo, 'switch', '-q', 'feature');
  return repo;
}

const deps = { git, shell: { runShell }, log: () => {} };

test('a lockfile-only conflict is regenerated and the merge committed, with nothing for the agent', async () => {
  const repo = await diverged(false);
  const merge = await mergeBase(deps, repo, 'main');
  assert.deepEqual(merge, { clean: true, conflicted: [], regenerated: ['pnpm-lock.yaml'] });
  const lock = await readFile(join(repo, 'pnpm-lock.yaml'), 'utf8');
  assert.doesNotMatch(lock, /^(<<<<<<<|>>>>>>>)/m);
  assert.match(lock, /lockfileVersion/);
  assert.equal(sh(repo, 'status', '--porcelain').trim(), '');
  assert.match(sh(repo, 'log', '-1', '--format=%P'), / /, 'the merge commit has two parents');
});

test('with other conflicts, the lockfile is resolved and staged, and only the others go to the agent', async () => {
  const repo = await diverged(true);
  const merge = await mergeBase(deps, repo, 'main');
  assert.deepEqual(merge, { clean: false, conflicted: ['notes.md'], regenerated: ['pnpm-lock.yaml'] });
  assert.match(sh(repo, 'diff', '--name-only', '--cached'), /pnpm-lock\.yaml/);
  assert.doesNotMatch(await readFile(join(repo, 'pnpm-lock.yaml'), 'utf8'), /^<<<<<<</m);
});

/**
 * A repository where both sides changed different lines of `src.txt` (which merges cleanly) and so
 * both regenerated `gen/a.txt` and `gen/b.txt` (its first and last line) from it, which conflict.
 */
async function divergedGenerated() {
  const repo = await mkdtemp(join(tmpdir(), 'factory-merge-gen-'));
  sh(repo, 'init', '-q', '-b', 'main');
  sh(repo, 'config', 'user.name', 't');
  sh(repo, 'config', 'user.email', 't@example.com');
  const side = async (first: string, last: string) => {
    await writeFile(join(repo, 'src.txt'), `${first}\n2\n3\n4\n${last}\n`);
    // One generated line from the whole source: any change on either side conflicts here.
    await writeFile(join(repo, 'gen', 'a.txt'), `${first} ${last}\n`);
    await writeFile(join(repo, 'gen', 'b.txt'), `${first} ${last}\n`);
  };
  await mkdir(join(repo, 'gen'));
  await side('one', 'three');
  sh(repo, 'add', '.');
  sh(repo, 'commit', '-qm', 'base');
  sh(repo, 'switch', '-qc', 'feature');
  await side('ONE', 'three');
  sh(repo, 'commit', '-qam', 'feature');
  sh(repo, 'switch', '-q', 'main');
  await side('one', 'THREE');
  sh(repo, 'commit', '-qam', 'main');
  sh(repo, 'switch', '-q', 'feature');
  return repo;
}

test('a conflict on generated files is regenerated by the profile rule, run once, and the merge committed', async () => {
  const repo = await divergedGenerated();
  const runs = join(await mkdtemp(join(tmpdir(), 'factory-merge-runs-')), 'runs');
  const rules = [
    {
      paths: ['gen/**'],
      command: `L=$(sed -n '1p;$p' src.txt | paste -sd ' ' -); echo "$L" > gen/a.txt; echo "$L" > gen/b.txt; echo run >> '${runs}'`,
    },
  ];
  const merge = await mergeBase(deps, repo, 'main', rules);
  assert.deepEqual(merge, { clean: true, conflicted: [], regenerated: ['gen/a.txt', 'gen/b.txt'] });
  assert.equal(await readFile(join(repo, 'gen', 'a.txt'), 'utf8'), 'ONE THREE\n');
  assert.equal(await readFile(join(repo, 'gen', 'b.txt'), 'utf8'), 'ONE THREE\n');
  assert.equal(await readFile(runs, 'utf8'), 'run\n', 'the command runs once per rule');
  assert.equal(sh(repo, 'status', '--porcelain').trim(), '');
  assert.match(sh(repo, 'log', '-1', '--format=%P'), / /, 'the merge commit has two parents');
});

test('when the regenerate command fails, its files go to the agent with the merge left open', async () => {
  const repo = await divergedGenerated();
  const logs: string[] = [];
  const merge = await mergeBase({ ...deps, log: (line: string) => logs.push(line) }, repo, 'main', [
    { paths: ['gen/*.txt'], command: 'echo broken >&2; exit 3' },
  ]);
  assert.deepEqual(merge, { clean: false, conflicted: ['gen/a.txt', 'gen/b.txt'], regenerated: [] });
  assert.ok(
    logs.some((line) => /gen\/a\.txt/.test(line) && /broken/.test(line)),
    logs.join('\n'),
  );
  assert.ok(sh(repo, 'rev-parse', '-q', '--verify', 'MERGE_HEAD').trim(), 'the merge stays open');
  assert.match(await readFile(join(repo, 'gen', 'a.txt'), 'utf8'), /^<<<<<<< /m, 'the agent sees both sides');
});
